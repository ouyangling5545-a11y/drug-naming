# ── Query helpers ──

_stem_index: dict[str, INNStem] | None = None
_chinese_index: dict[str, list[INNStem]] | None = None


def _build_indices() -> None:
    """Lazily build lookup indices on first access."""
    global _stem_index, _chinese_index
    if _stem_index is not None:
        return
    _stem_index = {}
    _chinese_index = {}
    for s in STEMS:
        key = s.stem.strip("-").lower()
        _stem_index[key] = s
        if s.chinese:
            _chinese_index.setdefault(s.chinese, []).append(s)


def get_by_stem(stem: str) -> INNStem | None:
    """Look up a stem by its core text (e.g. 'tinib', '-tinib', 'mab')."""
    _build_indices()
    return _stem_index.get(stem.strip("-").lower())


def get_by_chinese(cn: str) -> list[INNStem]:
    """Find stems whose Chinese translation contains the given text."""
    _build_indices()
    results = []
    for chn, stems in _chinese_index.items():
        if cn in chn:
            results.extend(stems)
    return results


def get_all() -> list[INNStem]:
    """Return all stems."""
    return STEMS
